// SHA-256 (FIPS 180-4) y MD5 (RFC 1321) síncronos sobre el texto en UTF-8.
// El motor de la consola es síncrono, así que no puede usar crypto.subtle (asíncrono);
// el resultado coincide con sha256sum/md5sum/certutil sobre un fichero con ese contenido.

const encoder = new TextEncoder();

function toHex(bytes: Uint8Array): string {
  return Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('');
}

